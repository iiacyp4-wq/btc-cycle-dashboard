/* collect-hashribbon.js — daily collector for the Hash Ribbon indicator (ADR-005).
   Run:  node scripts/collect-hashribbon.js     (Node 18+, no npm packages)
   Rule (Capriole "Hash Ribbons", TradingView kT7jIvqv):
     hr30 = 30-day SMA of hash rate · hr60 = 60-day SMA
     capitulation  = hr30 crosses UNDER hr60          → gray circles while hr30 < hr60 and falling
     recovering    = still under, but hr30 rising     → green circles
     recovery      = hr30 crosses back OVER hr60      → last green circle
     buy           = first day after recovery where price SMA10 > SMA20 → blue circle
   Recomputed from full history every run (simple, idempotent). */

const fs = require('fs');
const path = require('path');

const DATA_DIR = path.join(__dirname, '..', 'data');
const CSV = path.join(DATA_DIR, 'hashribbon.csv');
const JS = path.join(DATA_DIR, 'hashribbon.js');
const OUTPUT_FROM = '2011-07-18';

async function fetchJSON(url) {
  const r = await fetch(url, { headers: { 'user-agent': 'btc-cycle-dashboard/1.0' } });
  if (!r.ok) throw new Error(`HTTP ${r.status} for ${url}`);
  const j = await r.json();
  if (j.error) throw new Error(JSON.stringify(j.error));
  return j;
}

/* Primary: CoinMetrics Community — HashRate (TH/s) + PriceUSD, daily, full history. */
async function coinmetrics() {
  let url = 'https://community-api.coinmetrics.io/v4/timeseries/asset-metrics'
    + '?assets=btc&metrics=HashRate,PriceUSD&frequency=1d&start_time=2010-07-18&page_size=10000';
  let data = [];
  while (url) { const j = await fetchJSON(url); data = data.concat(j.data); url = j.next_page_url; }
  return data.filter(r => r.HashRate && r.PriceUSD)
    .map(r => ({ date: r.time.slice(0, 10), hr: +r.HashRate, price: +r.PriceUSD }));
}

/* Fallback: blockchain.com charts (hash-rate in TH/s, market-price in USD). */
async function blockchaincom() {
  const [h, p] = await Promise.all([
    fetchJSON('https://api.blockchain.info/charts/hash-rate?timespan=all&format=json'),
    fetchJSON('https://api.blockchain.info/charts/market-price?timespan=all&format=json'),
  ]);
  const day = ts => new Date(ts * 1000).toISOString().slice(0, 10);
  const price = new Map(p.values.map(v => [day(v.x), v.y]));
  return h.values.map(v => ({ date: day(v.x), hr: v.y, price: price.get(day(v.x)) })).filter(r => r.price);
}

/* ---------- indicator ---------- */

function computeRibbon(rows, source) {
  const sma = (arr, n, i) => i + 1 < n ? null : arr.slice(i + 1 - n, i + 1).reduce((a, b) => a + b, 0) / n;
  const hrs = rows.map(r => r.hr), ps = rows.map(r => r.price);
  const out = [];
  let inCap = false, recovered = false, capStart = null, lastBuy = null;
  for (let i = 0; i < rows.length; i++) {
    const s = sma(hrs, 30, i), l = sma(hrs, 60, i);
    if (s == null || l == null) continue;
    const sp = sma(hrs, 30, i - 1), lp = sma(hrs, 60, i - 1);
    const p10 = sma(ps, 10, i), p20 = sma(ps, 20, i);
    let cross = '', marker = '';
    if (sp != null && sp >= lp && s < l) { inCap = true; recovered = false; capStart = rows[i].date; cross = 'capitulation'; }
    if (inCap && sp != null && sp <= lp && s > l) { inCap = false; recovered = true; cross = 'recovery'; marker = 'green'; }
    if (inCap) marker = s > sp ? 'green' : 'gray';
    if (recovered && p10 > p20) { marker = 'blue'; cross = 'buy'; recovered = false; lastBuy = rows[i].date; }
    out.push({
      date: rows[i].date,
      hr30: +(s / 1e6).toFixed(4), hr60: +(l / 1e6).toFixed(4),   // EH/s
      price: +rows[i].price.toFixed(2), p10: +p10.toFixed(2), p20: +p20.toFixed(2),
      phase: inCap ? 'capitulation' : (recovered ? 'recovered' : 'normal'),
      marker, cross, status: 'ok', source,
    });
  }
  return out.filter(r => r.date >= OUTPUT_FROM);
}

/* ---------- output ---------- */

function writeAll(rows) {
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const cols = ['date', 'hr30', 'hr60', 'price', 'p10', 'p20', 'phase', 'marker', 'cross', 'status', 'source', 'note'];
  fs.writeFileSync(CSV, cols.join(',') + '\n' + rows.map(r => cols.map(c => r[c] ?? '').join(',')).join('\n') + '\n');
  fs.writeFileSync(JS, '/* generated by scripts/collect-hashribbon.js — do not edit */\nwindow.HASHRIBBON_ROWS = '
    + JSON.stringify(rows.map(({ note, ...r }) => r)) + ';\n');
}

function readLast() {
  if (!fs.existsSync(JS)) return [];
  const m = fs.readFileSync(JS, 'utf8').match(/window\.HASHRIBBON_ROWS = (\[.*\]);/s);
  return m ? JSON.parse(m[1]) : [];
}

(async () => {
  let raw = [], source = 'coinmetrics', err = '';
  try { raw = await coinmetrics(); }
  catch (e1) {
    err = 'coinmetrics: ' + e1.message;
    try { raw = await blockchaincom(); source = 'blockchaincom'; }
    catch (e2) { err += ' | blockchaincom: ' + e2.message; }
  }

  let rows;
  if (raw.length) rows = computeRibbon(raw, source);
  else {
    // Both sources failed → keep last good data and append a visible `missing` row (PRD guardrail).
    rows = readLast();
    const y = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
    if (rows.length && rows.at(-1).date < y) rows.push({ date: y, phase: '', marker: '', cross: '', status: 'missing', source: '-', note: err });
  }
  writeAll(rows);

  const last = rows.at(-1);
  const lastBuy = [...rows].reverse().find(r => r.cross === 'buy');
  console.log(`[hashribbon] rows=${rows.length} · source=${source} · latest=${last.date} phase=${last.phase} hr30=${last.hr30} hr60=${last.hr60} · lastBuy=${lastBuy ? lastBuy.date : '-'}${err ? ' · ' + err : ''}`);
  if (!raw.length) process.exitCode = 1;
})();
